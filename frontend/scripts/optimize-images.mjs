// Re-encodes images in public/images (max 1600px wide, mozjpeg) and writes tiny blur placeholders
// to src/lib/image-placeholders.ts. Run with `npm run images:optimize` after adding images.
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const root = path.resolve(import.meta.dirname, "..");
const dir = path.join(root, "public", "images");
const out = path.join(root, "src", "lib", "image-placeholders.ts");

const files = (await readdir(dir)).filter((f) => /\.(jpe?g|png|webp)$/i.test(f)).sort();
const entries = [];

for (const file of files) {
  const filePath = path.join(dir, file);
  const input = await readFile(filePath);
  const before = input.length;

  if (/\.jpe?g$/i.test(file)) {
    const optimized = await sharp(input)
      .rotate()
      .resize({ width: 1600, withoutEnlargement: true })
      .jpeg({ quality: 80, mozjpeg: true, progressive: true })
      .toBuffer();
    if (optimized.length < before) await writeFile(filePath, optimized);
    console.log(
      `${file}: ${Math.round(before / 1024)}KB -> ${Math.round(Math.min(before, optimized.length) / 1024)}KB`,
    );
  }

  const blur = await sharp(input).resize(16, 16, { fit: "inside" }).webp({ quality: 40 }).toBuffer();
  entries.push(`  "/images/${file}": "data:image/webp;base64,${blur.toString("base64")}",`);
}

await writeFile(
  out,
  `// Generated by scripts/optimize-images.mjs — do not edit by hand.\nexport const imagePlaceholders: Record<string, string> = {\n${entries.join("\n")}\n};\n`,
);
console.log(`Wrote ${entries.length} placeholders to ${path.relative(root, out)}`);
